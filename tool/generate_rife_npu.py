"""Fuse RIFE's four CNN blocks without changing the original weight stream.

No ML converter or new model weights are needed. Deconvolution/warp/resizing
stay in ncnn. Run from the repository root; --check verifies committed output.
"""
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "assets/models/rife-v4.6/flownet.param"
assert hashlib.sha256(MODEL.read_bytes()).hexdigest() == "724569596bcd1e7b9fa50455c604777ebed99746d2ef40aa86e31b5725f1053c"


def parse(line):
    words = line.split()
    ni, no = map(int, words[2:4])
    return (words[0], words[1], words[4:4+ni], words[4+ni:4+ni+no],
            dict(v.split("=", 1) for v in words[4+ni+no:]))


lines = MODEL.read_text().splitlines()[2:]
groups, rewritten = [], []
i = 0
while i < len(lines):
    layer = parse(lines[i])
    if layer[0] != "Convolution":
        rewritten.append(lines[i]); i += 1; continue
    start = i
    while parse(lines[i])[0] != "Deconvolution":
        assert parse(lines[i])[0] in {"Convolution", "Split", "BinaryOp", "ReLU"}
        i += 1
    group = [parse(line) for line in lines[start:i]]
    input_name, output_name = group[0][2][0], group[-1][3][0]
    internal = {name for op in group for name in op[3]} - {output_name}
    assert not any(internal.intersection(parse(line)[2]) for line in lines[:start]+lines[i:])
    aliases, ops = {input_name: 0}, []
    for kind, name, inputs, outputs, p in group:
        if kind == "Split":
            for name in outputs: aliases[name] = aliases[inputs[0]]
            continue
        a = aliases[inputs[0]]
        if kind == "Convolution":
            assert set(p) <= {"0", "1", "3", "4", "5", "6", "9", "-23310"}
            out, k, stride, pad = (int(p.get(key, default)) for key, default in [("0",0),("1",0),("3",1),("4",0)])
            assert p["5"] == "1" and int(p.get("9", 0)) in (0, 2)
            activation = int(p.get("9", 0))
            slope = float(p.get("-23310", "1,0").split(",")[1]) if activation else 0
            ops.append((0,a,0,out,k,stride,pad,int(p["6"]),activation,slope))
        elif kind == "BinaryOp":
            assert len(inputs) == 2 and not p  # residual add only
            ops.append((1,a,aliases[inputs[1]],0,0,0,0,0,0,0))
        else:
            ops.append((2,a,0,0,0,0,0,0,0,float(p.get("0",0))))
        aliases[outputs[0]] = len(ops)
    assert aliases[output_name] == len(ops)
    rewritten.append(f"oplayer.NpuBlock npu_block_{len(groups)} 1 1 {input_name} {output_name} 0={len(groups)}")
    groups.append(ops)
assert len(groups) == 4

header = "// Generated by tool/generate_rife_npu.py from the pinned RIFE v4.6 graph.\n#pragma once\n"
header += "struct NpuOp { int kind,a,b,out,kernel,stride,pad,weights,activation; float slope; };\n"
header += "struct NpuBlockSpec { const NpuOp* ops; int count; };\n"
for index, ops in enumerate(groups):
    header += f"static const NpuOp npu_ops_{index}[] = {{\n"
    for op in ops:
        header += "  {"+",".join(str(x) for x in op[:-1])+f",{op[-1]:.9f}f"+"},\n"
    header += "};\n"
header += "static const NpuBlockSpec npu_blocks[] = {\n"+"".join(f"  {{npu_ops_{i}, {len(g)}}},\n" for i,g in enumerate(groups))+"};\n"
blobs = {name for line in rewritten for name in parse(line)[3]}
param = f"7767517\n{len(rewritten)} {len(blobs)}\n"+"\n".join(rewritten)+"\n"
outputs = {
    ROOT/"packages/ai_frame_engine/native/rife_npu_blocks.h": header,
    ROOT/"assets/models/rife-v4.6/flownet-npu.param": param,
}
for path, content in outputs.items():
    data = content.encode()
    if "--check" in sys.argv:
        assert path.read_bytes() == data, f"Regenerate {path}"
    else:
        path.write_bytes(data)
    print(path.name, hashlib.sha256(data).hexdigest())
